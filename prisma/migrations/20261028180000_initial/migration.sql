-- Bloqueio da turma serializa cadastros, transferências e reduções de capacidade.
CREATE FUNCTION verificar_capacidade_aluno() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ocupacao integer; capacidade_max integer;
BEGIN
 IF TG_OP = 'UPDATE' THEN
  PERFORM id_turma FROM turma WHERE id_turma IN (OLD.turma_id, NEW.turma_id) ORDER BY id_turma FOR UPDATE;
 ELSE
  PERFORM id_turma FROM turma WHERE id_turma = NEW.turma_id FOR UPDATE;
 END IF;
 IF NEW.ativo AND NEW.status = 'MATRICULADO' THEN
  SELECT capacidade INTO capacidade_max FROM turma WHERE id_turma = NEW.turma_id;
  SELECT count(*) INTO ocupacao FROM aluno WHERE turma_id = NEW.turma_id AND ativo AND status = 'MATRICULADO' AND id_aluno <> NEW.id_aluno;
  IF ocupacao >= capacidade_max THEN RAISE EXCEPTION 'Capacidade da turma excedida' USING ERRCODE = '23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER aluno_capacidade BEFORE INSERT OR UPDATE OF turma_id, ativo, status ON aluno FOR EACH ROW EXECUTE FUNCTION verificar_capacidade_aluno();
CREATE FUNCTION verificar_reducao_capacidade() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.capacidade < (SELECT count(*) FROM aluno WHERE turma_id = NEW.id_turma AND ativo AND status = 'MATRICULADO') THEN
  RAISE EXCEPTION 'Capacidade inferior à ocupação atual' USING ERRCODE = '23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER turma_capacidade BEFORE UPDATE OF capacidade ON turma FOR EACH ROW EXECUTE FUNCTION verificar_reducao_capacidade();

